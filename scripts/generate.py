#!/usr/bin/env python3
"""Render Robert's local CV content using the original hmemcpy/cv design."""
import json
from pathlib import Path
from datetime import date

ROOT = Path(__file__).resolve().parents[1]
cv = json.loads((ROOT / 'data/cv.json').read_text())
ESCAPE = {'\\': r'\textbackslash{}', '&': r'\&', '%': r'\%', '$': r'\$', '#': r'\#', '_': r'\_', '{': r'\{', '}': r'\}', '~': r'\textasciitilde{}', '^': r'\textasciicircum{}'}
def tex(value):
    return ''.join(ESCAPE.get(c, c) for c in (value or ''))
def link(url, label):
    if not url.startswith('https://'):
        raise ValueError('Public links must use HTTPS')
    return r'\href{' + tex(url) + '}{' + tex(label) + '}'
def period(value):
    return tex(value).replace(' - ', '--')

def row(label, text, gap='3pt'):
    return r'\textsc{' + tex(label) + ':} & ' + text + r'\\[' + gap + ']'

profile = cv['profile']
# Preserve the upstream template's fonts, rules, date columns, icons and tag colors.
preamble = (ROOT / 'template.tex').read_text().split(r'\begin{document}')[0]
preamble = preamble.replace('Alex Example', tex(profile['fullName']))
preamble = preamble.replace(r'\usepackage{longtable}', r'\usepackage{longtable,array}')
preamble = preamble.replace(r'\hypersetup{colorlinks,breaklinks,urlcolor=linkcolor, linkcolor=linkcolor}',
    r'\hypersetup{colorlinks,breaklinks,urlcolor=linkcolor,linkcolor=linkcolor,pdftitle={Robert Wevamwo - Curriculum Vitae},pdfauthor={Robert Wevamwo}}')
reviewed = date.fromisoformat(cv['reviewedOn'])
preamble = preamble.replace(r'\fancyfoot[R]{\today}', r'\fancyfoot[R]{' + reviewed.strftime('%B ') + str(reviewed.day) + reviewed.strftime(', %Y') + '}')
parts = ['% Generated by scripts/generate.py from data/cv.json; preserves the MIT-licensed upstream design.', preamble, r'\begin{document}',
    r'\par{\centering{\Huge\textsc{' + tex(profile['fullName']) + r'}}\bigskip\par}',
    r'\hrule\vspace{0.5em}', r'\begin{tabular}{rl}',
    row('Location', tex(profile['location']), '0pt'),
    row('Contact', r'\faEnvelopeO{} ' + link(cv['siteUrl'] + '/contact', 'Get in touch'), '0pt'),
    row('Links', r'\faHome{} ' + link(cv['siteUrl'], 'wevbert.pages.dev') + ' | ' + r'\faGithub{} ' + link('https://github.com/wevbert', 'github') + ' | ' + r'\faLinkedin{} ' + link(profile['linkedInUrl'], 'linkedin'), '0pt'),
    r'\end{tabular}', r'\section{Summary}', r'\begin{tabular}{p{0.9\textwidth}}',
    tex(cv['summary']), r'\end{tabular}',
    r'\section{Work Experience \hfill{\normalfont\footnotesize\itshape (full details on LinkedIn)}}',
    r'\begin{longtable}{r|p{0.72\textwidth}}']
keywords = [
    ['security-architecture', 'zero-trust', 'infoblox', 'microsegmentation'],
    ['soc-leadership', 'crowdstrike', 'siem', 'incident-response'],
    ['security-monitoring', 'vulnerability-management', 'triage'],
]
for i, role in enumerate(cv['experience'][:3]):
    parts.append(r'\textsc{' + period(role['period']) + r'} & \job{' + tex(role['title']) + '}{' + tex(role['organization']) + r'} \\')
    for j, paragraph in enumerate(role['highlights']):
        parts.append('& ' + tex(paragraph) + (r'\\[6pt]' if j < len(role['highlights']) - 1 else r'\sotagrow{' + ','.join(keywords[i]) + '}'))
    if i < 2:
        parts.append(r'\sep')
parts += [r'\end{longtable}', r'\section{Recognition}', r'\begin{tabular}{p{0.9\textwidth}}', tex('; '.join(cv['honors'])), r'\end{tabular}', r'\newpage', r'\begingroup',
    r'\titlespacing{\section}{0pt}{1em}{4pt}',
    r'\section{Earlier Experience \hfill{\normalfont\footnotesize\itshape (full details on LinkedIn)}}',
    r'\begin{longtable}{@{}p{0.20\textwidth}|p{0.29\textwidth}|p{0.43\textwidth}@{}}']
for role in cv['experience'][3:]:
    parts.append(r'\textsc{' + period(role['period']) + r'} & \textbf{' + tex(role['title']) + r'}\newline ' + tex(role['organization']) + ' & ' + tex(role.get('pdfSummary', ' '.join(role['highlights']))) + r'\\[8pt]')
parts += [r'\end{longtable}', r'\section{Technical Profile}', r'\begin{tabular}{r p{0.72\textwidth}}']
labels=['Architecture','Operations','Platforms','Governance','Systems']
for label, group in zip(labels, cv['skills']):
    parts.append(row(label, tex(', '.join(group['items']))))
parts += [row('Languages', tex(', '.join(cv['languages']))), r'\end{tabular}', r'\section{Certifications}', r'\begin{tabular}{r p{0.72\textwidth}}',
    row('Security', 'CISSP, CCSP, SSCP, Certified in Cybersecurity (CC) --- (ISC)2'),
    row('Cloud', 'Google Cloud Professional Security Engineer'),
    row('Governance', r'PECB ISO/IEC 27001:2022 Lead Implementer'),
    row('Operations', 'EC-Council Certified SOC Analyst; CompTIA Security+'),
    r'\end{tabular}', r'\section{Education}', r'\begin{tabular}{r p{0.72\textwidth}}']
for entry in cv['education']:
    parts.append(r'\textsc{' + period(entry['period']) + r'} & \textbf{' + tex(entry['qualification']) + '}, ' + tex(entry['institution']) + '. ' + tex(entry['note']) + r'.\\[4pt]')
parts += [r'\end{tabular}', r'\section{Leadership \& Community}', r'\begin{tabular}{r p{0.72\textwidth}}']
for entry in cv['leadership']:
    parts.append(row(entry['organization'].replace('Access Bank Ghana', 'Volunteering').replace('CyberFirst Bootcamp Series','CyberFirst'), r'\textbf{' + tex(entry['title']) + '} (' + period(entry['period']) + '). ' + tex(entry.get('pdfSummary', entry['description'])), '4pt'))
parts += [r'\end{tabular}', r'\endgroup', r'\end{document}']
(ROOT / 'cv.tex').write_text('\n'.join(parts) + '\n')
print('Updated cv.tex with the original template design and Robert\'s content.')
