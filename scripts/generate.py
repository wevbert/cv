#!/usr/bin/env python3
"""Render the fork's LaTeX CV from a public Sanity snapshot (stdlib only)."""
import argparse
import json
from pathlib import Path
from urllib.parse import urlencode
from urllib.request import urlopen

ROOT = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser()
parser.add_argument('--refresh', action='store_true', help='Refresh the snapshot from published Sanity content')
args = parser.parse_args()
if args.refresh:
    config = json.loads((ROOT / 'sanity.config.json').read_text())
    query = '''*[_id == "curriculumVitae"][0]{...,certifications[]->{_id,title,issuingOrganization,verificationUrl},"profile":*[_id == "profile"][0]{fullName,location,linkedInUrl}}'''
    url = f"https://{config['projectId']}.api.sanity.io/v2025-02-19/data/query/{config['dataset']}?" + urlencode({'query': query, 'perspective': 'published'})
    with urlopen(url, timeout=30) as response:
        cv = json.load(response)['result']
    if not cv or not cv.get('experience') or not cv.get('profile', {}).get('fullName'):
        raise SystemExit('Published CV/profile is incomplete; existing snapshot preserved.')
    for key in ('_createdAt', '_updatedAt', '_rev'):
        cv.pop(key, None)
    cv['siteUrl'] = config['siteUrl']
    (ROOT / 'data/cv.json').write_text(json.dumps(cv, indent=2, ensure_ascii=False) + '\n')
else:
    cv = json.loads((ROOT / 'data/cv.json').read_text())

ESCAPE = {'\\': r'\textbackslash{}', '&': r'\&', '%': r'\%', '$': r'\$', '#': r'\#', '_': r'\_', '{': r'\{', '}': r'\}', '~': r'\textasciitilde{}', '^': r'\textasciicircum{}'}
def tex(value):
    return ''.join(ESCAPE.get(c, c) for c in (value or ''))
def link(url, label):
    if not url.startswith('https://'):
        raise ValueError('Public links must use HTTPS')
    return r'\href{' + tex(url) + '}{' + tex(label) + '}'
def bullets(values):
    return '\n'.join(r'\item ' + tex(x) for x in values)

profile = cv['profile']
parts = [r'''% !TEX TS-program = lualatex
% Generated by scripts/generate.py. Edit the Sanity CV document or data/cv.json.
% Adapted from hmemcpy/cv (MIT), based on Alessandro Plasmati's Professional CV.
\documentclass[a4paper,10pt]{article}
\usepackage[margin=1.65cm,footskip=24pt]{geometry}
\usepackage{libertine}
\usepackage[table]{xcolor}
\usepackage{longtable,array,enumitem}
\usepackage{fancyhdr,lastpage,titlesec,hyperref}
\definecolor{ink}{HTML}{0F1725}
\definecolor{muted}{HTML}{475569}
\definecolor{linkcolor}{HTML}{036985}
\color{ink}
\hypersetup{colorlinks,breaklinks,urlcolor=linkcolor,linkcolor=linkcolor,
  pdftitle={Robert Wevamwo - Curriculum Vitae},pdfauthor={Robert Wevamwo},
  pdfsubject={Cybersecurity, cloud security, security architecture and SOC leadership}}
\pagestyle{fancy}
\fancyhf{}
\fancyfoot[L]{\small Robert Wevamwo}
\fancyfoot[C]{\small Page \thepage\ of \pageref*{LastPage}}
\fancyfoot[R]{\small October 2026}
\renewcommand{\headrulewidth}{0pt}
\renewcommand{\footrulewidth}{0.3pt}
\setlength{\parindent}{0pt}
\setlength{\parskip}{3pt}
\setlength{\tabcolsep}{8pt}
\setlength{\LTpre}{3pt}
\setlength{\LTpost}{3pt}
\setlist[itemize]{leftmargin=1.1em,nosep,topsep=3pt,itemsep=3pt,parsep=0pt}
\titleformat{\section}{\large\sffamily\bfseries}{}{0em}{}[\titlerule]
\titlespacing{\section}{0pt}{11pt}{5pt}
\arrayrulecolor{black!25}
\newcommand{\job}[1]{{\sffamily\bfseries #1}}
\newcommand{\period}[1]{{\small\color{muted} #1}}
\begin{document}
''']
parts += [r'{\Huge\scshape ' + tex(profile['fullName']) + r'}\par',
          r'\vspace{4pt}{\large\sffamily ' + tex(cv['headline']) + r'}\par',
          r'\vspace{5pt}' + tex(profile['location']) + r'\quad | \quad ' + link(cv['siteUrl'] + '/cv', 'Portfolio & CV') + r'\quad | \quad ' + link(cv['siteUrl'] + '/contact', 'Contact') + r'\quad | \quad ' + link(profile['linkedInUrl'], 'LinkedIn'),
          r'\section{Professional Profile}', tex(cv['summary']), r'\section{Professional Experience}',
          r'\begin{longtable}{@{}>{\raggedright\arraybackslash}p{0.155\textwidth}|p{0.79\textwidth}@{}}']
for role in cv['experience']:
    parts += [r'\period{' + tex(role['period']) + r'} & \job{' + tex(role['title']) + r'}\newline ' + tex(role['organization']) + r'\enspace | \enspace ' + tex(role.get('location', '')) + r'\par', r'\begin{itemize}', bullets(role['highlights']), r'\end{itemize} \\[7pt]']
parts += [r'\end{longtable}', r'\newpage', r'\section{Expertise \& Tools}', r'\begin{longtable}{@{}>{\raggedright\arraybackslash}p{0.19\textwidth} p{0.76\textwidth}@{}}']
for group in cv.get('skills', []):
    parts.append(r'\textbf{' + tex(group['title']) + '} & ' + tex(', '.join(group['items'])) + r'\\[5pt]')
parts += [r'\end{longtable}', r'\section{Certifications}', r'\begin{itemize}']
parts += [r'\item ' + tex(c['title']) for c in cv.get('certifications', []) if c]
parts += [r'\end{itemize}', r'\section{Education}', r'\begin{longtable}{@{}>{\raggedright\arraybackslash}p{0.155\textwidth}|p{0.79\textwidth}@{}}']
for entry in cv.get('education', []):
    parts.append(r'\period{' + tex(entry['period']) + r'} & \job{' + tex(entry['qualification']) + r'}\newline ' + tex(entry['institution']) + r'\newline {\small\color{muted} ' + tex(entry.get('note', '')) + r'}\\[6pt]')
parts += [r'\end{longtable}', r'\section{Leadership \& Community}']
for entry in cv.get('leadership', []):
    parts += [r'\job{' + tex(entry['title']) + '} | ' + tex(entry['organization']) + r'\hfill\period{' + tex(entry['period']) + r'}\par', tex(entry['description']) + r'\par\vspace{4pt}']
parts += [r'\section{Recognition}', r'\begin{itemize}', bullets(cv.get('honors', [])), r'\end{itemize}', r'\vspace{7pt}\textbf{Languages:} ' + tex(', '.join(cv.get('languages', []))), r'\end{document}']
# The footer records the reviewed content date rather than the machine's build date.
from datetime import date
reviewed = date.fromisoformat(cv['reviewedOn']).strftime('%B %Y')
source = '\n'.join(parts).replace(r'\fancyfoot[R]{\small October 2026}', r'\fancyfoot[R]{\small ' + reviewed + '}') + '\n'
(ROOT / 'cv.tex').write_text(source)
print('Generated cv.tex from', 'Sanity' if args.refresh else 'data/cv.json')
